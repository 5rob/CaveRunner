// Which Dev knobs CaveRunner Auto's build actually reads (owner v1.0.57: colour the Dev panel by it). tools/build.js runs this
// first: it bundles src/main.js tree-shaken (only the code the game can reach), drops the knob tables (src/dev/knobs.js) and
// the panel's own UI (src/ui/devpanel.js), and looks in what's left for each knob: `DEV.key`, or its name as a string (kr('fireSpread'),
// jcol('jeColA'), FIRE_KNOB's 'fireGrass'; a range knob's Lo / Hi by its base name). Writes src/dev/autouse.js when the list changes.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(SRC, 'dev', 'autouse.js');
const SKIP = ['src/dev/knobs.js', 'src/dev/autouse.js', 'src/ui/devpanel.js'];

// every knob key: the real DEV_META (src/ bundled in memory, as the logic suites load it)
function knobKeys() { return require('../tests/load').DEV_META.map((/** @type {{ k: string }} */ m) => m.k); }

function scan() {
  const r = require('esbuild').buildSync({
    entryPoints: [path.join(SRC, 'main.js')], bundle: true, format: 'iife', charset: 'utf8', minify: false,
    treeShaking: true, write: false, logLevel: 'silent',
  });
  // the bundle's modules, each after its `// src/…` marker; keep all but SKIP
  const text = r.outputFiles[0].text.replace(/\r\n/g, '\n');
  let code = '', keep = true;
  for (const line of text.split('\n')) {
    const m = /^\s*\/\/ (src\/[\w/.-]+\.js)$/.exec(line);
    if (m) { keep = !SKIP.includes(m[1]); continue; }
    if (keep) code += line + '\n';
  }
  return knobKeys().filter(k => {
    const base = /(Lo|Hi)$/.test(k) ? k.slice(0, -2) : null;
    return new RegExp(`\\bDEV\\.${k}\\b|["'\`]${k}["'\`]`).test(code) || (!!base && new RegExp(`["'\`]${base}["'\`]|\\bDEV\\.${base}(Lo|Hi)\\b`).test(code));
  }).sort();
}

function write() {
  const keys = scan();
  const body = '// Generated by tools/autoknobs.js (tools/build.js runs it): the Dev knobs CaveRunner Auto\'s build reads. Don\'t edit.\n' +
    '// The Dev panel colours a knob by it (ui/devpanel.js).\n' +
    'export const AUTO_KNOBS = new Set([\n' + keys.map(k => `  '${k}',`).join('\n') + '\n]);\n';
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (old !== body) fs.writeFileSync(OUT, body);
  return keys;
}

module.exports = { scan, write, knobKeys };
if (require.main === module) console.log(write().length + ' knobs reach Auto, of ' + knobKeys().length);
