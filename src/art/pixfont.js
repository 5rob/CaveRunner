// each glyph: its width in pixels, and its runs of pixels [row, first column, length]
/** @type {Map<string, { w: number, runs: number[][] }>} */
const GLYPHS = new Map();
for (const [ch, src] of Object.entries(SRC)) {
  const rows = src.split('|'), runs = [];
  rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== '#') continue;
      let e = c;
      while (row[e + 1] === '#') e++;
      runs.push([r, c, e - c + 1]);
      c = e;
    }
  });
  GLYPHS.set(ch, { w: rows[0].length, runs });
}

// can the font draw every character of s?
/** @param {string} s */
export const pixHas = s => [...s].every(ch => GLYPHS.has(ch));

// s's width, for pixels px wide (one pixel between letters, plus the bold smear)
/** @param {string} s @param {number} px @param {number} [bold] */
export function pixWidth(s, px, bold = 0) {
  let w = 0;
  for (const ch of s) w += ((GLYPHS.get(ch) || GLYPHS.get(' '))?.w || 3) + 1 + bold;
  return Math.max(0, w - 1) * px;
}

// Draw s in the current fillStyle from x, its baseline at y (the bottom of the capitals), pixels
// px wide and ph tall, each smeared bold pixels to the right. Edges snap to 1/snap units so the
// pixels of a scaled canvas meet without seams
/** @param {CanvasRenderingContext2D} ctx @param {string} s @param {number} x @param {number} y @param {number} px @param {number} ph @param {number} [bold] @param {number} [snap] */
export function pixText(ctx, s, x, y, px, ph, bold = 0, snap = 4) {
  const q = (/** @type {number} */ v) => Math.round(v * snap) / snap, top = y - 7 * ph;
  for (const ch of s) {
    const g = GLYPHS.get(ch) || GLYPHS.get(' ');
    if (!g) continue;
    for (const [r, c, n] of g.runs) {
      const x0 = q(x + c * px), y0 = q(top + r * ph);
      ctx.fillRect(x0, y0, q(x + (c + n + bold) * px) - x0, q(top + (r + 1) * ph) - y0);
    }
    x += (g.w + 1 + bold) * px;
  }
}
